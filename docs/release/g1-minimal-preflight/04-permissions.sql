-- Effective CURRENT connection only; NEVER proves that this is the API principal.
-- No impersonation, permission changes, attempted DDL/DML or principal names.
SELECT code,status FROM (VALUES
 ('NO_DATABASE_CONTROL',CASE HAS_PERMS_BY_NAME(DB_NAME(),'DATABASE','CONTROL') WHEN 0 THEN 'PASS' WHEN 1 THEN 'FAIL' ELSE 'UNKNOWN' END),
 ('NO_DATABASE_ALTER',CASE HAS_PERMS_BY_NAME(DB_NAME(),'DATABASE','ALTER') WHEN 0 THEN 'PASS' WHEN 1 THEN 'FAIL' ELSE 'UNKNOWN' END),
 ('NO_CREATE_TABLE',CASE HAS_PERMS_BY_NAME(DB_NAME(),'DATABASE','CREATE TABLE') WHEN 0 THEN 'PASS' WHEN 1 THEN 'FAIL' ELSE 'UNKNOWN' END),
 ('NO_SCHEMA_ALTER',CASE HAS_PERMS_BY_NAME(N'dbo','SCHEMA','ALTER') WHEN 0 THEN 'PASS' WHEN 1 THEN 'FAIL' ELSE 'UNKNOWN' END),
 ('NO_REGISTRY_INSERT',CASE HAS_PERMS_BY_NAME(N'dbo.SchemaVersions','OBJECT','INSERT') WHEN 0 THEN 'PASS' WHEN 1 THEN 'FAIL' ELSE 'UNKNOWN' END),
 ('NO_REGISTRY_UPDATE',CASE HAS_PERMS_BY_NAME(N'dbo.SchemaVersions','OBJECT','UPDATE') WHEN 0 THEN 'PASS' WHEN 1 THEN 'FAIL' ELSE 'UNKNOWN' END),
 ('NO_REGISTRY_DELETE',CASE HAS_PERMS_BY_NAME(N'dbo.SchemaVersions','OBJECT','DELETE') WHEN 0 THEN 'PASS' WHEN 1 THEN 'FAIL' ELSE 'UNKNOWN' END),
 ('API_PRINCIPAL_BINDING','UNKNOWN'),
 ('API_OPERATION_PERMISSION_MATRIX','UNKNOWN')
) AS c(code,status) ORDER BY code;
