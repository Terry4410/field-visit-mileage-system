#!/usr/bin/env python3
"""Read-only, non-deploy P1 schema parity inventory. NOT a migration rehearsal.

Checks only version 1800_003 deployment-site definitions against the EF model.
The output deliberately cannot say PARITY PASS while migration-only SQL exists.
"""
from __future__ import annotations

import argparse
import json
import os
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[2]
DDL = ROOT / "database/migrations/1800_003_deployment_sites/Up.sql"
MODEL = ROOT / "backend/src/FieldVisit.Infrastructure/AppDbContext.cs"
DDL_009 = ROOT / "database/migrations/1800_009_one_stop_route_attempt_constraint/Up.sql"
DDL_010 = ROOT / "database/migrations/1800_010_background_mileage_reason_constraint/Up.sql"

TABLES = {
    "DeploymentSites": "DeploymentSite",
    "DeploymentSiteLocationAssignments": "DeploymentSiteLocationAssignment",
    "TeamDeploymentSiteAssignments": "TeamDeploymentSiteAssignment",
    "EmploymentDeploymentSiteAssignments": "EmploymentDeploymentSiteAssignment",
}
UNIQUE = (
    "UQ_DeploymentSites_Center_Code",
    "UQ_DeploymentSiteLocationAssignments_Start",
    "UQ_TeamDeploymentSiteAssignments_Start",
    "UQ_EmploymentDeploymentSiteAssignments_Start",
)
TRIGGERS = (
    "TR_DeploymentSites_CenterPeriod",
    "TR_DeploymentSiteLocations_NoOverlap",
    "TR_TeamDeploymentSites_NoOverlap",
    "TR_EmploymentDeploymentSites_SameSiteNoOverlap",
    "TR_EmploymentDeploymentSites_OnePrimary",
    "TR_TeamCenterAssignments_ProtectTeamSites",
    "TR_DeploymentSites_ProtectTeamSites",
)
CHECKS = (
    "CK_DeploymentSites_Dates",
    "CK_DeploymentSiteLocationAssignments_Dates",
    "CK_TeamDeploymentSiteAssignments_Dates",
    "CK_EmploymentDeploymentSiteAssignments_Dates",
)

def analyze(sql: str, ef: str, sha: str = "LOCAL",
            sql_009: str | None = None, sql_010: str | None = None) -> dict:
    rows: list[dict[str, str]] = []
    failures: list[str] = []

    def record(kind: str, name: str, status: str, note: str) -> None:
        rows.append({"kind": kind, "name": name, "status": status, "note": note})

    for table, entity in TABLES.items():
        in_sql = bool(re.search(r"CREATE\s+TABLE\s+dbo\." + re.escape(table) + r"\b", sql, re.I))
        in_ef = bool(re.search(r'Entity<' + entity + r'>\(e\s*=>\s*\{\s*e\.ToTable\("' + table + r'"', ef))
        if not in_sql or not in_ef:
            failures.append("table-mapping missing: " + table)
        record("TABLE_MAPPING", table, "MATCH" if in_sql and in_ef else "BLOCKED",
               "DDL table and EF ToTable name only; not a column/type equivalence check")
        model_block = re.search(r"Entity<" + entity + r">\(e\s*=>\s*\{(.*?)\n\s*\}\);", ef, re.S)
        sql_table = re.search(r"CREATE\s+TABLE\s+dbo\." + table + r"\s*\((.*?)\n\s*\);", sql, re.S | re.I)
        sql_rv = bool(sql_table and re.search(r"\bRowVersion\s+ROWVERSION\s+NOT\s+NULL\b", sql_table.group(1), re.I))
        ef_rv = bool(model_block and re.search(r"\.Property\(x\s*=>\s*x\.RowVersion\)\.IsRowVersion\(\)\.IsConcurrencyToken\(\)", model_block.group(1)))
        if not (sql_rv and ef_rv):
            failures.append("rowversion mapping missing: " + table)
        record("ROWVERSION", table, "MATCH" if sql_rv and ef_rv else "BLOCKED",
               "Static token/concurrency declaration; storage runtime not compared")

    for name in UNIQUE:
        in_sql = bool(re.search(r"CONSTRAINT\s+" + re.escape(name) + r"\s+UNIQUE\s*\(", sql, re.I))
        in_ef = bool(re.search(r'\.HasDatabaseName\("' + name + r'"\)', ef))
        if not (in_sql and in_ef):
            failures.append("unique mapping missing: " + name)
        record("UNIQUE_NAME", name, "MATCH" if in_sql and in_ef else "BLOCKED",
               "Names match; index key/order/collation and actual DDL require SQL catalog verification")

    for name in CHECKS:
        in_sql = bool(re.search(r"CONSTRAINT\s+" + name + r"\s+CHECK\s*\(", sql, re.I))
        in_ef = bool(re.search(r'HasCheckConstraint\("' + name + r'"', ef))
        if not in_sql:
            failures.append("migration CHECK missing: " + name)
        record("DATE_CHECK", name, "MATCH" if in_sql and in_ef else
               ("DIFFERENCE" if in_sql else "BLOCKED"),
               "Migration CHECK is not generated by current EF EnsureCreated model" if in_sql and not in_ef else
               "Static presence only; catalog validation required")

    for name in TRIGGERS:
        in_sql = bool(re.search(r"CREATE\s+TRIGGER\s+dbo\." + name + r"\b", sql, re.I))
        if not in_sql:
            failures.append("migration trigger missing: " + name)
        record("TRIGGER", name, "DIFFERENCE" if in_sql else "BLOCKED",
               "SQL-only migration trigger; EF EnsureCreated does not execute migration Up.sql")

    # Static, nonexecuting inventory of migration-only 009/010 CHECK changes.
    # These definitions are intentionally NOT enforced by EF EnsureCreated.
    if sql_009 is not None:
        valid_009 = bool(re.search(
            r"ALTER\s+TABLE\s+dbo\.RouteCalculationAttempts\s+WITH\s+CHECK\s+ADD"
            r"\s+CONSTRAINT\s+CK_RouteCalculationAttempts_StopCount\s+CHECK\s*\(\s*StopCount\s*>=\s*1\s*\)",
            sql_009, re.I))
        if not valid_009:
            failures.append("1800_009 StopCount >= 1 constraint missing or drifted")
        record("MIGRATION_ONLY_CHECK", "1800_009:StopCount>=1",
               "DIFFERENCE" if valid_009 else "BLOCKED",
               "Migration-only SQL CHECK; EF EnsureCreated does not enforce it")
    if sql_010 is not None:
        reason_block = re.search(
            r"CONSTRAINT\s+CK_RouteCalculationAttempts_Reason\s+CHECK\s*\((.*?)\)\s*;",
            sql_010, re.I | re.S)
        expected_reasons = (
            "VisitorCalculate", "LeaderRetry",
            "CorrectionRecalculate", "BackgroundMileageJob")
        found_reasons = re.findall(
            r"CalculationReason\s*=\s*N'([^']+)'",
            reason_block.group(1), re.I) if reason_block else []
        valid_010 = (len(found_reasons) == len(expected_reasons)
                     and set(found_reasons) == set(expected_reasons))
        if not valid_010:
            failures.append("1800_010 reason CHECK missing or drifted")
        record("MIGRATION_ONLY_CHECK", "1800_010:CalculationReason",
               "DIFFERENCE" if valid_010 else "BLOCKED",
               "Four migration-only allowed reasons; EF EnsureCreated does not enforce them")

    record("FK_INDEX_INCLUDED_COLUMNS", "1800_003", "NEEDS VALIDATION",
           "Names alone do not establish FK delete rules, included index columns or SQL CHECK enforcement")
    record("TRIP_SNAPSHOT_AUDIT_HISTORY", "1600_*..1800_010", "NEEDS VALIDATION",
           "Migration-owned columns, backfill, uniqueness and audit/history invariants not fully diffed")
    record("MIGRATION_CHAIN", "1600_*..1800_010", "BLOCKED",
           "No executable baseline or full disposable migration-chain rehearsal authorized/performed")
    return {
        "kind": "B4_SCHEMA_PARITY_STATIC_INVENTORY_NONRELEASE",
        "source_sha": sha,
        "scope": "1800_003 static EF comparison; optional 1800_009/010 migration-only CHECK inventory",
        "status": "FAIL_CLOSED" if failures else "PASS_WITH_KNOWN_DIFFERENCES",
        "schema_parity": "NOT_VERIFIED",
        "migration_executed": False,
        "b4_formal_accepted": "0/22",
        "b3_flag": "OFF",
        "live_session_guard_default": "OFF",
        "manager_grant": "BLOCKED",
        "approve_apply": "DENY_ALL",
        "business_uat": "HOLD",
        "production": "HARD_HOLD",
        "rows": rows,
        "failures": failures,
    }

def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--report", required=True)
    parser.add_argument("--summary", required=True)
    args = parser.parse_args()
    result = analyze(DDL.read_text(encoding="utf-8"), MODEL.read_text(encoding="utf-8"),
                     os.getenv("GITHUB_SHA", "LOCAL"),
                     DDL_009.read_text(encoding="utf-8"), DDL_010.read_text(encoding="utf-8"))
    output = Path(args.report)
    summary = Path(args.summary)
    output.parent.mkdir(parents=True, exist_ok=True)
    summary.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(json.dumps(result, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    lines = ["### P1: static SQL migration / EF gap inventory (NO MIGRATION)",
             "Status: " + result["status"],
             "Full migration schema parity: NOT_VERIFIED",
             "1800_003 compared statically; 1800_009/010 migration-only CHECKs inventoried; full parity NOT VERIFIED.",
             "| Kind | Name | Assessment |",
             "| --- | --- | --- |"]
    lines += [f'| {x["kind"]} | {x["name"]} | {x["status"]} |' for x in result["rows"]]
    lines += ["", "B4 0/22; B3 OFF; LiveSessionGuard default OFF; Approve/Apply DENY ALL.",
              "VAL-B1-002 BLOCKED; 1800_011 NOT AUTHORIZED; Business UAT HOLD; Production HARD HOLD."]
    if result["failures"]:
        lines.append("FAIL_CLOSED: " + "; ".join(result["failures"]))
    summary.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))
    return 1 if result["failures"] else 0

if __name__ == "__main__":
    sys.exit(main())
